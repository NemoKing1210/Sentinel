const FILE_KIND_ICON: Record<FileKind, string> = {
  folder: 'folder',
  archive: 'archive',
  image: 'image',
  video: 'video',
  audio: 'audio',
  code: 'code',
  executable: 'executable',
  document: 'doc',
  spreadsheet: 'spreadsheet',
  presentation: 'presentation',
  font: 'doc',
  disk: 'archive',
  database: 'database',
  text: 'doc',
  unknown: 'file',
};

export function fileIconName(kind?: FileKind): string {
  return FILE_KIND_ICON[kind ?? 'unknown'] ?? 'file';
}

function variantKey(size: IconSize | undefined): 16 | 20 | 24 {
  if (size === undefined) return 16;
  if (size <= 16) return 16;
  if (size <= 20) return 20;
  return 24;
}

export function Icon({ name, size }: { name: string; size?: IconSize }) {
  const variants = ICONS[name] ?? ICONS.grid;
  const variant = variants[variantKey(size)] ?? variants[24];
  return createElement(variant, {
    className: 'glyph',
    'aria-hidden': true,
    style: size ? { width: size, height: size } : undefined,
  });
}
